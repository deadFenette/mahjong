/* ============================================================
   SOUNDS/WIN.JS — Победа
   Арпеджио по пентатонике (ступени 0-2-3-5-7-8-10), затем
   тёплый аккорд с длинным отзвуком и басом. Тон ниже и мягче
   прежнего (верхняя нота — не C7, а ~C6): не царапает слух.
   Учитывает флаг winSoundEnabled — если выключен, тишина.
   ============================================================ */

Sounds.win = {
  name: 'Победа',
  desc: 'Арпеджио и тёплый аккорд с отзвуком',
  play: function (ctx, kit, opts) {
    if (opts && opts.winSoundEnabled === false) return;
    const run = [0, 2, 3, 5, 7, 8, 10];
    run.forEach((deg, i) => {
      kit.bell(kit.note(deg), 0.5, 0.075, i * 0.13, 0.45);
    });
    const t = run.length * 0.13 + 0.05;
    kit.bell(kit.note(5), 1.8, 0.07, t, 0.6);
    kit.bell(kit.note(7), 1.8, 0.065, t + 0.02, 0.6);
    kit.bell(kit.note(10), 2.0, 0.07, t + 0.04, 0.6);
    kit.bell(kit.note(0), 2.2, 0.08, t, 0.5);
  },
};
