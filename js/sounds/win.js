/* ============================================================
   SOUNDS/WIN.JS — Победа
   Восходящая мелодия C5-E5-G5-C6-E6-G6-C7.
   Учитывает флаг winSoundEnabled — если выключен, тишина.
   ============================================================ */

Sounds.win = {
  name: 'Победа',
  desc: 'Восходящая мелодия при завершении раскладки',
  play: function (ctx, playTone, opts) {
    // opts.winSoundEnabled — если false, звук не играется
    if (opts && opts.winSoundEnabled === false) return;
    const notes = [
      [523.25, 0],    // C5
      [659.25, 0.15], // E5
      [783.99, 0.3],  // G5
      [1046.5, 0.45], // C6
      [1318.51, 0.65], // E6
      [1567.98, 0.85], // G6
      [2093.0, 1.1],   // C7
    ];
    notes.forEach(([f, t]) => playTone(f, 0.3, 'sine', 0.18, t));
  },
};
