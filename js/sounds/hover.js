/* ============================================================
   SOUNDS/HOVER.JS — Наведение на фишку
   Чистый синус без обертонов — тихая «капля»: мягкая атака 4 мс,
   затухание ~110 мс, лёгкий хвост реверба. Нота — из тональности
   играющей музыки (ступень 10 пентатоники), поэтому не режет слух.
   Троттлинг 60 мс — на быстром движении мыши звуки не сливаются.
   Играет только над свободными фишками (см. render.js) — звук
   сам подсказывает, что фишку можно взять.
   ============================================================ */

Sounds.hover = {
  name: 'Наведение',
  desc: 'Чистая тихая нота при наведении на свободную фишку',
  _lastAt: 0, // троттлинг — не чаще раза в 60 мс
  play: function (ctx, kit) {
    const now = Date.now();
    if (now - Sounds.hover._lastAt < 60) return;
    Sounds.hover._lastAt = now;
    kit.pure(kit.note(10), 0.11, 0.04, 0, 0.12);
  },
};
