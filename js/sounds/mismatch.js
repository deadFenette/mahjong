/* ============================================================
   SOUNDS/MISMATCH.JS — Не совпало
   Мягкий низкий «пуф» вместо прежней пилы: глухой тук и тёмный
   шорох. Информирует, но не наказывает.
   ============================================================ */

Sounds.mismatch = {
  name: 'Не совпало',
  desc: 'Мягкий низкий пуф при несовпадении',
  play: function (ctx, kit) {
    kit.thump(kit.note(-2), 0.10, 0, 0.16);
    kit.noise(0.08, 0.03, 0, { type: 'lowpass', freq: 600, q: 0.7 });
  },
};
