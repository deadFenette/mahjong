/* ============================================================
   SOUNDS/HINT.JS — Подсказка
   Три тихих искорки вверх (ступени 8-10-12) с длинным отзвуком.
   ============================================================ */

Sounds.hint = {
  name: 'Подсказка',
  desc: 'Три тихие искорки с отзвуком',
  play: function (ctx, kit) {
    kit.bell(kit.note(8), 0.5, 0.055, 0, 0.5);
    kit.bell(kit.note(10), 0.55, 0.05, 0.09, 0.5);
    kit.bell(kit.note(12), 0.7, 0.045, 0.18, 0.55);
  },
};
