/* ============================================================
   SOUNDS/COMBO.JS — Комбо-серия
   Восходящая гамма из нот тональности. Чем длиннее серия, тем
   выше старт и тем больше нот (3 → 6). Ноты берутся по СТУПЕНЯМ
   пентатоники, а не умножением частоты — как бы ни росла серия,
   звук остаётся в строе музыки. Параметр mult: 2..8.
   ============================================================ */

Sounds.combo = {
  name: 'Комбо',
  desc: 'Гамма из нот тональности, растёт вместе с серией',
  play: function (ctx, kit, mult) {
    const m = Number(mult);
    const level = (Number.isInteger(m) && m >= 2) ? Math.min(m, 8) : 2;
    const count = Math.min(6, 3 + Math.floor((level - 1) / 2)); // 3 … 6 нот
    const base = 5 + Math.floor((level - 2) / 2);               // старт 5 … 8
    kit.tap(0.10, 0, 0.6);
    for (let i = 0; i < count; i++) {
      const last = i === count - 1;
      kit.bell(kit.note(base + i), last ? 0.6 : 0.3, 0.07 + i * 0.004,
        0.02 + i * 0.055, 0.4);
    }
  },
};
