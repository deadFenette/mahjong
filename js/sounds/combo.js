/* ============================================================
   SOUNDS/COMBO.JS — Комбо-серия
   Восходящая искристая фраза. Чем длиннее серия, тем выше тон.
   Ограничение ×8 — чтобы к ×8 звук оставался приятным.
   Параметр mult — множитель серии (2..8).
   ============================================================ */

Sounds.combo = {
  name: 'Комбо',
  desc: 'Искристая фраза, тон растёт с множителем серии',
  play: function (ctx, playTone, mult) {
    const m = Number(mult);
    const level = (Number.isInteger(m) && m >= 2) ? Math.min(m, 8) : 2;
    const k = 1 + (level - 2) * 0.06; // 1.0 … 1.36
    playTone(523.25 * k, 0.12, 'sine', 0.16);
    playTone(659.25 * k, 0.12, 'sine', 0.15, 0.05);
    playTone(783.99 * k, 0.18, 'sine', 0.17, 0.10);
    playTone(1046.5 * k, 0.26, 'sine', 0.15, 0.15);
  },
};
