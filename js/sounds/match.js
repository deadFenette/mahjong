/* ============================================================
   SOUNDS/MATCH.JS — Совпадение пары
   «Клац» двух фишек и восходящая трель из трёх тёплых нот
   тональности (ступени 5-7-8). Хвост уходит в реверб.
   ============================================================ */

Sounds.match = {
  name: 'Совпадение',
  desc: 'Стук фишек и мягкая восходящая трель',
  play: function (ctx, kit) {
    kit.tap(0.11, 0, 0.55);
    kit.bell(kit.note(5), 0.34, 0.075, 0.02, 0.35);
    kit.bell(kit.note(7), 0.34, 0.07, 0.07, 0.35);
    kit.bell(kit.note(8), 0.50, 0.075, 0.12, 0.40);
  },
};
