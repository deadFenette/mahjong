/* ============================================================
   SOUNDS/CLICK.JS — Выбор фишки
   Мягкое касание: глухой «тук» фишки по войлоку + тёплый
   колокольчик из тональности музыки с лёгким отзвуком.
   ============================================================ */

Sounds.click = {
  name: 'Выбор фишки',
  desc: 'Мягкое касание фишки и тёплый колокольчик',
  play: function (ctx, kit) {
    kit.tap(0.13, 0, 0.25);
    kit.bell(kit.note(7), 0.38, 0.05, 0.012, 0.28);
  },
};
