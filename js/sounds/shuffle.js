/* ============================================================
   SOUNDS/SHUFFLE.JS — Перемешать
   Шуршание фишек по столу: «ковёр» из шума с ползущим фильтром
   и россыпь коротких стуков по панораме (раньше — шесть писклявых
   тонов). Заканчивается тихой нотой — «разложили».
   ============================================================ */

Sounds.shuffle = {
  name: 'Перемешать',
  desc: 'Шуршание и россыпь стуков фишек',
  play: function (ctx, kit) {
    kit.noise(0.55, 0.035, 0, { type: 'bandpass', freq: 700, freqTo: 2200, q: 0.9, wet: 0.15 });
    for (let i = 0; i < 9; i++) {
      const at = 0.05 + i * 0.05 + Math.random() * 0.02;
      kit.noise(0.05, 0.04 + Math.random() * 0.03, at, {
        type: 'bandpass', freq: 900 + Math.random() * 1800, q: 1.4,
        pan: (Math.random() * 2 - 1) * 0.7,
      });
      if (i % 3 === 0) kit.thump(kit.note(-2 + i / 3), 0.05, at, 0.07);
    }
    kit.bell(kit.note(7), 0.5, 0.04, 0.55, 0.4);
  },
};
