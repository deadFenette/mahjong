/* ============================================================
   SOUNDS/SHUFFLE.JS — Перемешать
   Шуршание — 6 коротких шумов 400-800 Hz.
   ============================================================ */

Sounds.shuffle = {
  name: 'Перемешать',
  desc: 'Шуршание при перемешивании фишек',
  play: function (ctx, playTone) {
    for (let i = 0; i < 6; i++) {
      playTone(400 + Math.random() * 400, 0.05, 'triangle', 0.06, i * 0.04);
    }
  },
};
