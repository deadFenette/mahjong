/* ============================================================
   SOUNDS/BLOCKED.JS — Фишка занята
   Глухой короткий «ток» — «сюда нельзя». Без тона и без упрёка.
   ============================================================ */

Sounds.blocked = {
  name: 'Фишка занята',
  desc: 'Глухой «ток» при клике по заблокированной фишке',
  play: function (ctx, kit) {
    kit.thump(kit.note(-3), 0.08, 0, 0.07);
    kit.noise(0.04, 0.025, 0, { type: 'lowpass', freq: 500, q: 0.7 });
  },
};
