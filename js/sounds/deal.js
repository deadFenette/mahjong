/* ============================================================
   SOUNDS/DEAL.JS — Раздача
   Каскад из десяти тихих стуков: фишки ложатся на стол одна за
   другой, тон слегка растёт. Звучит при начале и продолжении
   партии, синхронно с каскадной анимацией.
   ============================================================ */

Sounds.deal = {
  name: 'Раздача',
  desc: 'Каскад мягких стуков — фишки ложатся на стол',
  play: function (ctx, kit) {
    for (let i = 0; i < 10; i++) {
      kit.tap(0.035 + i * 0.002, i * 0.045, 0.25 + i * 0.04);
    }
    kit.bell(kit.note(7), 0.55, 0.04, 0.5, 0.4);
  },
};
