/* ============================================================
   SOUNDS/DEAL.JS — Раздача
   v43: волна раздачи снова диагональная (слева-вверху →
   вправо-вниз), стуки panорамированы в такт: слева → вправо.
   Плотность и яркость растут к концу волны. Финальный
   колокольчик — доска готова.
   ============================================================ */

Sounds.deal = {
  name: 'Раздача',
  desc: 'Каскад стуков вдоль волны: слева-вверху → вправо-вниз',
  play: function (ctx, kit) {
    // Панорама повторяет ход волны: левый край → центр → правый
    const pans = [-0.45, -0.35, -0.22, -0.1, 0, 0.1, 0.22, 0.34, 0.42, 0.2];
    for (let i = 0; i < 10; i++) {
      kit.tap(0.03 + i * 0.002, i * 0.072, 0.22 + i * 0.035, pans[i]);
    }
    // «Доска собрана» — мягкий акцент после последней фишки
    kit.bell(kit.note(7), 0.5, 0.035, 0.8, 0.3);
  },
};
