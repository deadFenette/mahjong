/* ============================================================
   SOUNDS/STAMP.JS — «Шлепок печати» (v42)
   Глухой, телесный удар: печать-штамп пришлёпывается на место
   в тосте о достижении. Низкий тук + короткий шорох бумаги —
   никакого «дзынь», вес и финальность.
   ============================================================ */

Sounds.stamp = {
  name: 'Печать',
  desc: 'Глухой шлепок — тост о достижении пришлёпывается штампом',
  play: function (ctx, kit) {
    // Тело печати: низкий, почти деревянный тук
    kit.thump(88, 0.5, 0, 0.13);
    // Подтверждающий призвук — чуть выше, тише, чуть позже
    kit.thump(132, 0.22, 0.045, 0.08);
    // Шорох бумаги/лака — приглушённый шум с низкой частотой
    kit.noise(0.07, 0.22, 0.005, { type: 'lowpass', freq: 320, q: 0.6 });
  },
};
