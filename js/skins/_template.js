/* ============================================================
   SKINS/_template.js — ШАБЛОН нового скина фишек (НЕ подключён)

   Файлы с «_» в начале имени игра и тесты игнорируют. Чтобы сделать
   свой скин: скопируйте этот файл в js/skins/<id>.js, поменяйте id,
   название и функцию face(), затем добавьте две строки (см. README.md):
     index.html:  <script src="js/skins/<id>.js"></script>   (после classic.js)
     sw.js:       './js/skins/<id>.js',
   Всё остальное — карточка в настройках, образцы, превью, тост,
   проверка выбранного скина, ленивая сборка — сделает реестр Tileset.
   Проверка: в консоли браузера  Tileset.validate('<id>')  → [] если всё верно,
   а тест tests/skins-registry.test.js сам проверит подключение файла.
   ============================================================ */

Tileset.register({
  id: 'example',                 // a-z, 0-9, дефис; должен совпадать с именем файла
  name: 'Пример',                // название на карточке и в тосте «Скин фишек: …»
  desc: 'Что отличает этот скин', // подпись на карточке
  order: 100,                    // порядок в списке (classic 10, ornate 20, pictures 30, clear 40)

  // Вариант А (обычный): только рисунок лица. 144 фишки, имена и правила
  // совпадения соберёт TilesetCore. face вызывается один раз на ВИД фишки.
  //   suit: 'dots' | 'bamboo' | 'characters' | 'winds' | 'dragons' | 'flowers' | 'seasons'
  //   rank: 1–9 для мастей; 'E','S','W','N' для ветров; 'R','G','W' для драконов;
  //         1–4 для цветов и сезонов
  face: function (suit, rank) {
    return TilesetCore.svg(
      '<text x="50" y="72" text-anchor="middle" font-size="44" fill="#333">' + rank + '</text>');
  },

  // Свои названия фишек (их показывают «Лупа» и подсказки) — необязательно:
  // names: { dots: ['Яблоко', …9 имён], winds: { E: 'Солнце', … } },

  // Вариант Б (полный контроль): вместо face — create() → { tiles, isMatch, groups },
  // как в js/skins/classic.js и ornate.js.
});
